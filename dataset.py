"""OMuleT dataset access helpers.

The real OMuleT dataset (arXiv:2411.19352) is Roblox-internal and not publicly
released; ``data/omulet/`` holds a schema-exact stand-in generated by
``generate_omulet_data.py``. Replace the files with the real ones to swap in.
"""
import csv
import json
import os
from typing import Any, Dict, List


def load_game_catalog(path: str = "data/omulet/game_catalog.csv") -> List[Dict[str, str]]:
    """Return the game catalog as a list of dict rows."""
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def load_omulet_requests(path: str = "data/omulet/requests.json") -> List[Dict[str, Any]]:
    """Return the OMuleT requests (request_id, query, ground_truth_ids)."""
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def has_omulet_data() -> bool:
    """True if the stand-in OMuleT files are present."""
    return os.path.exists("data/omulet/game_catalog.csv") and os.path.exists(
        "data/omulet/requests.json"
    )
